// 本機真實瀏覽器驗證。PLAYWRIGHT_MODULE 可指定已安裝的 playwright 絕對路徑。
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.TEST_BROWSER ? {executablePath:process.env.TEST_BROWSER} : {})});
  const context = await browser.newContext({viewport:{width:1440,height:1000},locale:'zh-TW',acceptDownloads:true});
  const page = await context.newPage();
  const base = process.env.TEST_URL || 'http://127.0.0.1:8011';
  const errors=[];
  page.on('pageerror',error => errors.push(error.message));
  await context.route('**/*', async route => {
    const url=route.request().url();
    if (process.env.TEST_FEISHU_MOCK==='1' && url.startsWith(base+'/auth/feishu/start?')) {
      // 先讓真實後端建立 state 與瀏覽器 Cookie，再模擬飛書返回。
      // maxRedirects:0 避免測試程式沿後端 302 真正連入飛書。
      const authorization=await route.fetch({maxRedirects:0});
      assert.equal(authorization.status(),302);
      const params=new URL(authorization.headers().location).searchParams;
      assert.equal(params.get('code_challenge_method'),'S256');
      assert(params.get('state') && params.get('code_challenge'));
      const callback=new URL(params.get('redirect_uri'));
      assert.equal(callback.origin,base);
      callback.searchParams.set('state',params.get('state'));
      callback.searchParams.set('code','browser_mock_code');
      await route.fulfill({status:200,headers:{'content-type':'text/html; charset=utf-8','set-cookie':authorization.headers()['set-cookie']},body:`<!doctype html><title>模擬飛書授權完成</title><script>location.replace(${JSON.stringify(callback.toString())})</script>`});
    } else if (url.startsWith(base) || url.startsWith('data:')) await route.continue();
    else await route.abort();
  });
  const artifacts=path.resolve('.test-artifacts');
  fs.mkdirSync(artifacts,{recursive:true});
  const click = async action => {
    const root=await page.locator('#modal-root .dialog').count() ? page.locator('#modal-root') : page;
    await root.locator(`[data-action="${action}"]`).first().click();
  };
  const waitToast = text => page.locator('#toast').filter({hasText:text}).waitFor({state:'visible'});
  const submit = () => page.locator('#modal-form button[type="submit"]').click();
  try {
    await page.goto(base);
    if (process.env.TEST_FEISHU_MOCK==='1') {
      await page.getByRole('heading',{name:'使用飛書帳號登入',exact:true}).waitFor();
      assert.equal((await page.request.get(base+'/api/v1/state')).status(),401);
      assert.equal((await page.request.get(base+'/api/v1/backup')).status(),401);
      await page.screenshot({path:path.join(artifacts,'07-feishu-login-desktop.png'),fullPage:true});
      await page.setViewportSize({width:390,height:844});
      await page.screenshot({path:path.join(artifacts,'08-feishu-login-mobile.png'),fullPage:true});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
      await page.setViewportSize({width:1440,height:1000});
      await page.locator('[data-testid="feishu-login"]').click();
    }
    await page.getByRole('heading',{name:'業務總覽',exact:true}).waitFor();
    assert.equal((await page.request.get(base+'/api/v1/state')).ok(),true);
    let state=await (await page.request.get(base+'/api/v1/state')).json();
    assert.equal(state.customers.length,0,'瀏覽器測試需使用空白的獨立資料目錄');
    await page.screenshot({path:path.join(artifacts,'01-empty-dashboard.png'),fullPage:true});
    await page.getByRole('link',{name:'線索池',exact:true}).click();
    await click('new-lead');
    await page.locator('[name="company"]').fill('瀏覽器測試公司');
    await page.locator('[name="contact"]').fill('林小姐');
    await page.locator('[name="phone"]').fill('13800138000');
    await page.locator('[name="region"]').fill('華東');
    await page.locator('[name="industry"]').fill('製造');
    await page.locator('[name="estimate"]').fill('100');
    await page.locator('[name="description"]').fill('第一階段建置系統，後續追加服務。');
    await submit();
    await waitToast('已登記到線索池');
    await page.locator('.card').filter({hasText:'瀏覽器測試公司'}).waitFor();
    assert((await page.locator('.card').innerText()).includes('13800138000'));
    await page.reload();
    await page.locator('.card').filter({hasText:'瀏覽器測試公司'}).waitFor();
    await click('assign');
    const assignedRep = state.reps.find(rep => rep.name === '測試業務員' && rep.selectable);
    assert(assignedRep,'驗收站應提供已審核並綁定飛書帳號的測試業務員');
    await page.locator('[name="rep_id"]').selectOption(String(assignedRep.id));
    await submit();
    await waitToast('已分配業務員');
    await page.getByRole('link',{name:'客戶',exact:true}).click();
    await page.getByRole('link',{name:'瀏覽器測試公司',exact:true}).click();
    await page.getByRole('heading',{name:'瀏覽器測試公司',exact:true}).waitFor();
    assert((await page.locator('.main').innerText()).includes('13800138000'));
    await click('meeting');
    await page.locator('[name="note"]').fill('第一次面談，確認合作需求。');
    await submit();
    await waitToast('跟進紀錄已儲存');
    await page.locator('.timeline-item').filter({hasText:'第一次面談'}).waitFor();
    await click('advance');
    await waitToast('已推進階段');
    await page.locator('[data-action="advance"]').filter({hasText:'進入報價確認'}).waitFor();
    await click('advance');
    await page.locator('[data-action="advance"]').filter({hasText:'進入合同簽約'}).waitFor();
    await click('advance');
    await page.locator('[data-action="new-contract"]').first().waitFor();
    await click('new-contract');
    await page.locator('[name="title"]').fill('第一份系統合同');
    await page.locator('[name="amount"]').fill('60');
    await submit();
    await waitToast('合同已建立');
    assert.equal(await page.locator('[data-action="complete"]').isDisabled(),true);
    await page.locator('#upload-file').setInputFiles({name:'已簽合同.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aXioAAAAASUVORK5CYII=','base64')});
    await page.locator('#upload-form button[type="submit"]').click();
    await waitToast('附件已上傳');
    assert.equal(await page.locator('[data-action="complete"]').isDisabled(),false);
    await page.locator('.preview img').waitFor();
    await click('complete');
    await page.locator('[name="signed_at"]').fill('2026-09-15');
    await page.locator('[name="confirmed"]').check();
    await submit();
    await waitToast('已完成簽約');
    await page.locator('#modal-root .tag-accent').filter({hasText:'簽約完畢'}).waitFor();
    await page.screenshot({path:path.join(artifacts,'02-signed-contract.png'),fullPage:true});
    const downloadEvent=page.waitForEvent('download');
    await page.getByRole('link',{name:'下載',exact:true}).click();
    const download=await downloadEvent;
    assert.equal(download.suggestedFilename(),'已簽合同.png');
    assert.equal(await download.failure(),null);
    await click('close');
    await click('new-contract');
    await page.locator('[name="title"]').fill('第二份追加合同');
    await page.locator('[name="amount"]').fill('40');
    await submit();
    await waitToast('合同已建立');
    await click('close');
    await page.getByRole('link',{name:'額度與指標',exact:true}).click();
    await page.getByRole('heading',{name:'額度與指標',exact:true}).waitFor();
    await page.locator('#year-select').selectOption('2026');
    await page.locator('#target-input').waitFor();
    await page.locator('#target-input').fill('2400');
    assert((await page.locator('#target-status').innerText()).includes('尚未儲存'));
    await click('save-target');
    await waitToast('年度指標已儲存');
    state=await (await page.request.get(base+'/api/v1/state?year=2026')).json();
    assert.equal(Number(state.summary.pending_amount),40);
    assert.equal(Number(state.summary.signed_amount),60);
    assert.equal(Number(state.targets.annual_target),2400);
    assert.equal(Number(state.targets.months[8].actual),60);
    assert.equal(state.customers[0].meetings,1);
    assert.equal(state.customers[0].contract_count,2);
    await page.screenshot({path:path.join(artifacts,'03-quota-desktop.png'),fullPage:true});
    await page.reload();
    await page.locator('#target-input').waitFor();
    assert.equal(Number(await page.locator('#target-input').inputValue()),2400);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(artifacts,'04-quota-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false,'手機版不應整頁橫向溢出');
    await page.getByRole('link',{name:'線索池',exact:true}).click();
    await page.locator('[data-action="lead-filter"][data-id="assigned"]').click();
    await page.screenshot({path:path.join(artifacts,'05-leads-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
    await page.setViewportSize({width:1440,height:1000});
    await page.getByRole('link',{name:'簽單／合同',exact:true}).click();
    await page.locator('#contract-search').fill('第二份');
    assert.equal(await page.locator('#contract-results tbody tr').count(),1);
    await page.locator('#contract-search').fill('');
    assert.equal(await page.locator('#contract-results tbody tr').count(),2);
    await page.screenshot({path:path.join(artifacts,'06-contracts-desktop.png'),fullPage:true});
    const backupEvent=page.waitForEvent('download');
    await page.getByRole('link',{name:'下載完整備份',exact:true}).click();
    const backup=await backupEvent;
    assert(backup.suggestedFilename().endsWith('.zip'));
    assert.equal(await backup.failure(),null);
    if (process.env.TEST_FEISHU_MOCK==='1') {
      await click('logout');
      await page.getByRole('heading',{name:'使用飛書帳號登入',exact:true}).waitFor();
      await page.getByRole('alert').filter({hasText:'已登出簽單台'}).waitFor();
      assert.equal((await page.request.get(base+'/api/v1/backup')).status(),401);
      await page.locator('[data-testid="feishu-login"]').click();
      await page.getByRole('heading',{name:'簽單／合同',exact:true}).waitFor();
      await context.clearCookies();
      await click('refresh');
      await page.getByRole('heading',{name:'使用飛書帳號登入',exact:true}).waitFor();
      assert.equal((await page.request.get(base+'/api/v1/state')).status(),401);
    }
    assert.deepEqual(errors,[],'頁面不應有 JavaScript 錯誤');
    fs.writeFileSync(path.join(artifacts,'browser-result.json'),JSON.stringify({ok:true,feishuProviderMock:process.env.TEST_FEISHU_MOCK==='1',checks:['未登入存取攔截','模擬飛書授權登入','空白資料','登記與刷新保存','已審核飛書業務員分配','面聊與推進','附件門檻','真實圖片預覽與下載','完成簽約','多份合同40待簽60已簽','年度指標試算與保存','手機版溢出','搜尋','完整備份下載','登出與登入失效'],javascriptErrors:errors},null,2));
    console.log('瀏覽器驗證通過：登記、分配、跟進、合同、附件、業績、備份及手機版。');
  } catch(error) {
    await page.screenshot({path:path.join(artifacts,'failure.png'),fullPage:true}).catch(()=>{});
    console.error('Test page:',page.url(),'JavaScript errors:',errors);
    console.error(error);
    process.exitCode=1;
  } finally {
    await browser.close();
  }
})();
